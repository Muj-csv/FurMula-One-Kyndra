/**
 * The provenance sentence, derived from the data rather than asserted.
 *
 * PRD §3.1 requires this wherever the cohort appears. Deriving it means the
 * claim cannot drift out of step with what is actually loaded.
 */
export function provenanceLabel(cohort: Cohort = COHORT): string {
  const surveyed = cohort.applicants.filter((applicant) => applicant.surveyed).length;
  const total = cohort.applicants.length;

  if (surveyed === 0) {
    return 'Simulated animals, placeholder households — the applicant survey has not been run yet.';
  }
  if (surveyed === total) {
    return `Simulated animals, real applicants — all ${total} households were surveyed.`;
  }
  return `Simulated animals; ${surveyed} of ${total} households are real people we surveyed, the rest are placeholders.`;
}
